export function AdminSidebar() {
  const pathname = usePathname();
  const { locale } = useLocale();
  const content = useDictionary(adminSidebarContent);

  const items: NavItem[] = [
    { href: `/${locale}/users`, label: content.users.value, icon: 'users', matchPrefix: true },
    { href: `/${locale}/statistics`, label: content.statistics.value, icon: 'statistics' },
    { href: `/${locale}/payments`, label: content.payments.value, icon: 'payments' },
    { href: `/${locale}/posts`, label: content.posts.value, icon: 'posts' },
  ];

  const renderNavItem = ({ href, label, icon, matchPrefix = false }: NavItem) => {
    const isActive = matchPrefix
      ? pathname === href || pathname.startsWith(`${href}/`)
      : pathname === href;

    return (
      <li key={href}>
        <Link
          href={href}
          className={`${styles.sidebar_button} ${isActive ? styles.active : ''}`.trim()}
        >
          <Icon icon={icon} active={isActive} />
          <span className={styles.sidebar_label}>{label}</span>
        </Link>
      </li>
    );
  };

  return (
    <div className={styles.sidebar_frame}>
      <SidebarShell primary={items.map(renderNavItem)} />
    </div>
  );
}
